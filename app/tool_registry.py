def page_config(slug: str) -> dict[str, object] | None:
    config = TOOLS.get(slug)
    if config is None:
        return None
    config = {**config, "rows": [dict(row) for row in config["rows"]]}
    if slug == "maternity":
        for row in config["rows"]:
            if row.get("name") == "due":
                row["value"] = (date.today() + timedelta(days=120)).isoformat()
    return config


def home_groups() -> list[dict[str, object]]:
    return [
        {
            "title": title,
            "tools": [TOOL_CARDS[slug] for slug in slugs],
        }
        for title, slugs in HOME_GROUPS
    ]
